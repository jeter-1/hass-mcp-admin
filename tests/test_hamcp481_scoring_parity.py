GOLDEN = json.loads(GOLDEN_PATH.read_text(encoding="ascii"))


def scoring_entity(record: dict) -> scoring.ScoringEntity:
    """The caller's mapping from a 9.2.0 enriched state record
    (fuzzy_search.py:303-331): the name falls back to the entity id,
    non-string aliases are dropped, and any ``_hidden_by`` value hides."""
    entity_id = record.get("entity_id", "")
    return scoring.ScoringEntity(
        entity_id=entity_id,
        friendly_name=record.get("attributes", {}).get("friendly_name", entity_id),
        aliases=tuple(alias for alias in record.get("_aliases", []) if isinstance(alias, str)),
        hidden=record.get("_hidden_by") is not None,
    )


ENTITIES = tuple(scoring_entity(record) for record in GOLDEN["entities"])


def entity_rows(matches) -> list[dict]:
    return [asdict(match) for match in matches]


def golden_mismatches() -> list[str]:
    """Every golden case the port does not reproduce, by section and index."""
    misses: list[str] = []
    for index, case in enumerate(GOLDEN["entity_search"]):
        rows = entity_rows(scoring.fuzzy_entity_matches(ENTITIES, case["query"], case["threshold"]))
        if rows != case["results"] or len(rows) != case["total"]:
            misses.append(f"entity_search[{index}]")
    for index, case in enumerate(GOLDEN["paged"]):
        rows = entity_rows(scoring.fuzzy_entity_matches(ENTITIES, case["query"], case["threshold"]))
        page = rows[case["offset"]:case["offset"] + case["limit"]]
        if page != case["results"] or len(rows) != case["total"]:
            misses.append(f"paged[{index}]")
    for index, case in enumerate(GOLDEN["tokenize"]):
        if scoring.tokenize(case["text"]) != case["tokens"]:
            misses.append(f"tokenize[{index}]")
    for index, case in enumerate(GOLDEN["name_scores"]):
        score = scoring.entity_name_score(
            case["entity_id"], case["friendly_name"], case["domain"], case["query"])
        if score != case["score"]:
            misses.append(f"name_scores[{index}]")
    for index, case in enumerate(GOLDEN["config_scores"]):
        score = scoring.config_match_score(
            GOLDEN["configs"][case["config"]], case["query"], case["exact_match"])
        if score != case["score"]:
            misses.append(f"config_scores[{index}]")
    for index, case in enumerate(GOLDEN["deep_matches"]):
        result = scoring.deep_match_score(
            case["entity_id"], case["friendly_name"], case["fuzzy_name_score"],
            case["config_match_score"], case["query_lower"], case["exact_match"],
            case["fuzzy_threshold"])
        if list(result) != case["result"]:
            misses.append(f"deep_matches[{index}]")
    for index, case in enumerate(GOLDEN["ratios"]):
        got = (scoring.ratio(case["query"], case["value"]),
               scoring.partial_ratio(case["query"], case["value"]),
               scoring.token_sort_ratio(case["query"], case["value"]))
        if got != (case["ratio"], case["partial_ratio"], case["token_sort_ratio"]):
            misses.append(f"ratios[{index}]")
    for index, case in enumerate(GOLDEN["hidden_penalty"]):
        if scoring.apply_hidden_penalty(case["score"], case["hidden_by"] is not None) != case["result"]:
            misses.append(f"hidden_penalty[{index}]")
    return misses


class GoldenProvenanceTests(unittest.TestCase):
    def test_provenance_pins_the_golden_the_generator_and_the_9_2_0_source(self) -> None:
        provenance = json.loads(PROVENANCE_PATH.read_text(encoding="ascii"))
        self.assertEqual(provenance["schema"], "hamcp481-scoring-provenance-v1")
        self.assertEqual(GOLDEN["schema"], "hamcp481-scoring-golden-v1")
        self.assertEqual(provenance["golden"]["sha256"],
                         hashlib.sha256(GOLDEN_PATH.read_bytes()).hexdigest())
        self.assertEqual(provenance["generator"]["sha256"],
                         hashlib.sha256(GENERATOR_PATH.read_bytes()).hexdigest())
        self.assertEqual(provenance["source"]["files"], GOLDEN["source"]["sha256"])
        self.assertEqual(provenance["source"]["executed"], [
            "src/ha_mcp/utils/fuzzy_search.py", "src/ha_mcp/tools/smart_search/_scoring.py",
        ])
        registry = json.loads(REGISTRY.read_text(encoding="utf-8"))
        release = next(r for r in registry["releases"] if r.get("version") == "9.2.0")
        for record in (provenance["source"], GOLDEN["source"]):
            self.assertEqual(record["version"], "9.2.0")
            self.assertEqual(record["commit"], release["source_commit"])
            self.assertEqual(record["repository"], release["source_repository"])

    def test_scoring_header_names_the_pinned_source_and_carries_the_license(self) -> None:
        doc = scoring.__doc__
        self.assertIn("ha-mcp 9.2.0, commit 51e3aac788482a081807591cd5d58d07dc4e540b", doc)
        for path, digest in GOLDEN["source"]["sha256"].items():
            self.assertIn(f"``{path}`` (sha256\n  {digest})", doc)
        self.assertIn("MIT License", doc)
        self.assertIn("Copyright (c) 2024 Julien", doc)
        self.assertIn('THE SOFTWARE IS PROVIDED "AS IS"', doc)

    def test_constants_equal_the_source(self) -> None:
        constants = GOLDEN["constants"]
        self.assertEqual(scoring.HIDDEN_SCORE_PENALTY, constants["HIDDEN_SCORE_PENALTY"])
        self.assertEqual(scoring.BM25_K1, constants["BM25_K1"])
        self.assertEqual(scoring.BM25_B, constants["BM25_B"])
        self.assertEqual(scoring.DEFAULT_FUZZY_THRESHOLD, constants["DEFAULT_FUZZY_THRESHOLD"])
        self.assertEqual(scoring.AREA_QUERY_FUZZY_THRESHOLD, 80)
        self.assertEqual(scoring.GRAPH_HIT_SCORE, 100)

    def test_golden_covers_every_bm25_and_fallback_branch(self) -> None:
        cases = GOLDEN["entity_search"]
        seen = {row["match_type"] for case in cases for row in case["results"]}
        self.assertEqual(seen, scoring.MATCH_TYPES - {"exact_match"})
        self.assertEqual({case["threshold"] for case in cases}, {60, 80})
        hidden_ids = {entity.entity_id for entity in ENTITIES if entity.hidden}
        self.assertTrue(any(row["entity_id"] in hidden_ids for case in cases for row in case["results"]))
        self.assertTrue(any(case["total"] == 0 for case in cases))
        fuzzy_config = [case["score"] for case in GOLDEN["config_scores"] if not case["exact_match"]]
        self.assertIn(0, fuzzy_config)
        self.assertIn(100, fuzzy_config)
        self.assertTrue(any(0 < score < 100 for score in fuzzy_config))
        self.assertTrue(any(score > 100 for score in (c["score"] for c in GOLDEN["name_scores"])))


class GoldenParityTests(unittest.TestCase):
    def test_every_golden_case_is_reproduced(self) -> None:
        self.assertEqual(golden_mismatches(), [])

    def test_entity_search_cases_one_by_one(self) -> None:
        for case in GOLDEN["entity_search"]:
            with self.subTest(query=case["query"], threshold=case["threshold"]):
                matches = scoring.fuzzy_entity_matches(ENTITIES, case["query"], case["threshold"])
                self.assertEqual(entity_rows(matches), case["results"])
                self.assertEqual(list(matches), sorted(matches, key=scoring.entity_order_key))

    def test_no_entities_and_blank_queries_match_nothing(self) -> None:
        self.assertEqual(GOLDEN["no_entities"], [[], 0])
        self.assertEqual(scoring.fuzzy_entity_matches((), "light"), ())
        for query in ("", "  ", "._- "):
            self.assertEqual(scoring.fuzzy_entity_matches(ENTITIES, query), ())

    def test_each_tuning_constant_is_load_bearing(self) -> None:
        mutations = {
            "BM25_K1": 2.0,
            "BM25_B": 0.75,
            "HIDDEN_SCORE_PENALTY": 10,
            "TYPO_FALLBACK_THRESHOLD": 70,
            "TYPO_FALLBACK_MIN_TOKEN_LENGTH": 3,
            "CONFIG_TYPO_THRESHOLD": 75,
        }
        for name, value in mutations.items():
            with self.subTest(constant=name), patch.object(scoring, name, value):
                self.assertNotEqual(golden_mismatches(), [], name)


class ExactMatchRuleTests(unittest.TestCase):
    """``exact_match`` true (search/entities.py:465-485 at 51e3aac7)."""

    def entity(self, entity_id="light.bed_light", name="Bed Light", hidden=False):
        return scoring.ScoringEntity(entity_id, name, hidden=hidden)

    def test_equal_id_or_name_scores_100(self) -> None:
        for query in ("light.bed_light", "bed light"):
            match = scoring.exact_entity_match(self.entity(), query)
            self.assertEqual((match.score, match.match_type, match.domain),
                             (100, "exact_match", "light"))

    def test_substring_of_id_or_name_scores_80(self) -> None:
        for query in ("bed_light", "light", "bed", "d l", "light.bed"):
            with self.subTest(query=query):
                self.assertEqual(scoring.exact_entity_match(self.entity(), query).score, 80)

    def test_case_is_folded_on_the_entity_side_only(self) -> None:
        entity = self.entity("light.Bed_Light", "BED LIGHT")
        self.assertEqual(scoring.exact_entity_match(entity, "bed light").score, 100)
        self.assertIsNone(scoring.exact_entity_match(entity, "BED"))

    def test_hidden_is_penalized_after_matching(self) -> None:
        hidden = self.entity(hidden=True)
        self.assertEqual(scoring.exact_entity_match(hidden, "bed light").score, 80)
        self.assertEqual(scoring.exact_entity_match(hidden, "bed").score, 60)

    def test_no_substring_no_match(self) -> None:
        for query in ("bedlight", "kitchen", "light bed", "bed  light"):
            with self.subTest(query=query):
                self.assertIsNone(scoring.exact_entity_match(self.entity(), query))

    def test_name_falls_back_to_id_by_caller(self) -> None:
        match = scoring.exact_entity_match(scoring.ScoringEntity("sensor.uptime", "sensor.uptime"),
                                           "sensor.uptime")
        self.assertEqual(match.score, 100)

    def test_order_is_score_then_entity_id(self) -> None:
        entities = (
            self.entity("light.b", "Bed"), self.entity("light.a", "Bed lamp"),
            self.entity("light.bed", "x", hidden=True), self.entity("light.c", "bed"),
        )
        matches = [m for m in (scoring.exact_entity_match(e, "bed") for e in entities) if m]
        ordered = [m.entity_id for m in sorted(matches, key=scoring.entity_order_key)]
        self.assertEqual(ordered, ["light.b", "light.c", "light.a", "light.bed"])


class InputContractTests(unittest.TestCase):
    def test_scoring_entity_refuses_untyped_values(self) -> None:
        bad = (
            {"entity_id": None, "friendly_name": "x"},
            {"entity_id": "light.x", "friendly_name": None},
            {"entity_id": "light.x", "friendly_name": "x", "aliases": ["a"]},
            {"entity_id": "light.x", "friendly_name": "x", "aliases": ("a", 7)},
            {"entity_id": "light.x", "friendly_name": "x", "hidden": "user"},
            {"entity_id": "light.x", "friendly_name": "x", "hidden": 1},
        )
        for kwargs in bad:
            with self.subTest(kwargs=kwargs), self.assertRaises(TypeError):
                scoring.ScoringEntity(**kwargs)

    def test_records_are_frozen(self) -> None:
        entity = scoring.ScoringEntity("light.x", "X")
        with self.assertRaises(AttributeError):
            entity.hidden = True


class ReachabilityTests(unittest.TestCase):
    def test_scoring_imports_only_the_standard_library_it_needs(self) -> None:
        tree = ast.parse((PACKAGE / "search/scoring.py").read_text(encoding="utf-8"))
        imported = set()
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                imported.update(alias.name for alias in node.names)
            elif isinstance(node, ast.ImportFrom):
                self.assertEqual(node.level, 0)
                imported.add(node.module)
        self.assertEqual(imported, {
            "__future__", "collections.abc", "dataclasses", "difflib", "math", "re", "typing",
        })

    def test_no_runtime_module_outside_search_imports_it(self) -> None:
        importers = []
        for path in PACKAGE.rglob("*.py"):
            relative = path.relative_to(PACKAGE.parent)
            if relative.parts[1] == "search":
                continue
            package = list(relative.parts[:-1])
            for node in ast.walk(ast.parse(path.read_text(encoding="utf-8"))):
                names = []
                if isinstance(node, ast.Import):
                    names = [alias.name for alias in node.names]
                elif isinstance(node, ast.ImportFrom):
                    base = package[:len(package) - node.level + 1] if node.level else []
                    module = ".".join(base + ([node.module] if node.module else []))
                    names = [module] + [f"{module}.{alias.name}" for alias in node.names]
                hits = [n for n in names
                        if n == "ha_mcp_engineering.search" or n.startswith("ha_mcp_engineering.search.")]
                if hits:
                    importers.append((str(relative), tuple(sorted(hits))))
        # HAMCP-501 W4: the gateway's sub-call page readers take the fixed W3
        # page contract, and nothing else outside search imports the package.
        subcalls = "ha_mcp_engineering.search.subcalls"
        self.assertEqual(importers, [("ha_mcp_engineering/providers/upstream_read_gateway.py", (
            subcalls, f"{subcalls}.BUCKETS", f"{subcalls}.MAX_SCAN_ROWS", f"{subcalls}.PAGE_SIZE",
            f"{subcalls}.PageResult", f"{subcalls}.page_arguments",
        ))])


