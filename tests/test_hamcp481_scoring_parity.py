        self.assertEqual(provenance["generator"]["sha256"],
                         hashlib.sha256(W1_GENERATOR_PATH.read_bytes()).hexdigest())
        self.assertEqual(provenance["generator"]["sha256"],
                         "8df4a13282b0564e58311dc7cbc64166230342505c222f301a464565ab7f9ff1")
        self.assertEqual(provenance["source"]["files"], golden["source"]["sha256"])
        registry = json.loads(REGISTRY.read_text(encoding="utf-8"))
