class BackupDispatchScopedCatalogTests(unittest.IsolatedAsyncioTestCase):
    def _provider(self, catalog: McpReadCatalog):
        transport = BackupTransport(catalog)
        provider = ReviewedOperationalBackupProvider()
        provider._transport = transport
        provider._state.configured = True
        return provider, transport

    async def test_unused_tool_drift_is_recorded_and_backup_dispatches_once(self):
        exact = exact_catalog(BACKUP_VERSION)
        exact_evidence = await self._provider(exact)[0].probe()
        provider, transport = self._provider(
            _with_tools(exact, _drift_description(exact.tools, "ha_get_state"))
        )
        result = await provider.create_full_backup("Exact backup", before_dispatch=lambda: None)
        self.assertEqual(transport.tool_name, "ha_manage_backup")
        self.assertEqual(
            transport.arguments,
            {"scope": "snapshot", "action": "create", "name": "Exact backup"},
        )
        self.assertEqual(
            result.provider_evidence.normalized_catalog_fingerprint,
            exact_evidence.normalized_catalog_fingerprint,
        )
        health = provider.health_snapshot()
        self.assertEqual(health["dispatch_count"], 1)
        self.assertEqual(health["fallback_count"], 0)
        admission = health["catalog_admission"]
        self.assertEqual(admission["status"], "accepted_unused_tool_drift")
        self.assertEqual(admission["exact_tools"], ["ha_manage_backup"])
        self.assertEqual(admission["unused_tool_drift_count"], 1)
        self.assertEqual(
            [
                (item["tool_name"], item["components"])
                for item in admission["unused_tool_drift"]
            ],
            [("ha_get_state", ["description_fingerprint", "runtime_contract_fingerprint"])],
        )

