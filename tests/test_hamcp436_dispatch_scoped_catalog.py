class AdmissionHelperTests(unittest.TestCase):
    def _validation(self, catalog: McpReadCatalog, *, server_name=None, protocol=None):
        return validate_reviewed_release_catalog(
            REGISTRY.by_version[catalog.server_version],
            observed_server_name=server_name or catalog.server_name,
            observed_upstream_version=catalog.server_version,
            observed_protocol_version=protocol or catalog.protocol_version,
            tools=catalog.tools,
        )

    def test_exact_catalog_keeps_the_previous_normalized_fingerprint(self):
        for catalog in (catalog_920(), exact_catalog(BACKUP_VERSION), exact_catalog("8.0.0")):
            with self.subTest(version=catalog.server_version):
                validation = self._validation(catalog)
                self.assertTrue(validation.valid)
                admission = admit_reviewed_catalog_for_dispatch(validation, ("ha_restart",))
                self.assertEqual(admission.status, "accepted_exact")
                self.assertTrue(admission.admitted)
                self.assertEqual(
                    admission.normalized_catalog_fingerprint,
                    validation.normalized_catalog_fingerprint,
                )
                self.assertEqual(admission.unused_tool_drift_count, 0)
                self.assertEqual(admission.as_dict()["model"], DISPATCH_SCOPED_CATALOG_ADMISSION_MODEL_V1)

    def test_unused_tool_drift_is_admitted_with_the_reviewed_fingerprint(self):
        validation = self._validation(catalog_920_component())
        admission = admit_reviewed_catalog_for_dispatch(
            validation, (RELOAD_TOOL, APP_ACTION_TOOL, APP_READ_TOOL)
        )
        self.assertEqual(admission.status, "accepted_unused_tool_drift")
        self.assertEqual(admission.exact_tools, tuple(sorted((RELOAD_TOOL, APP_ACTION_TOOL, APP_READ_TOOL))))
        self.assertEqual(admission.exact_tool_mismatches, ())
        self.assertEqual(admission.unused_tool_drift_count, 1)
        self.assertFalse(admission.unused_tool_drift_truncated)
        self.assertEqual(
            admission.normalized_catalog_fingerprint,
            validation.expected_normalized_catalog_fingerprint,
        )
        self.assertNotEqual(
            validation.normalized_catalog_fingerprint,
            validation.expected_normalized_catalog_fingerprint,
        )

    def test_drift_on_an_exact_tool_is_refused(self):
        validation = self._validation(catalog_920_component())
        admission = admit_reviewed_catalog_for_dispatch(validation, (REWRITTEN_TOOL, RELOAD_TOOL))
        self.assertEqual(admission.status, "rejected_dispatched_tool_mismatch")
        self.assertFalse(admission.admitted)
        self.assertEqual(admission.exact_tool_mismatches, (REWRITTEN_TOOL,))
        self.assertIsNone(admission.normalized_catalog_fingerprint)
        self.assertEqual(admission.unused_tool_drift, ())

    def test_unknown_or_empty_exact_set_is_refused(self):
        validation = self._validation(catalog_920())
        self.assertEqual(
            admit_reviewed_catalog_for_dispatch(validation, ()).status,
            "rejected_no_exact_tools",
        )
        unknown = admit_reviewed_catalog_for_dispatch(validation, ("ha_not_a_tool",))
        self.assertEqual(unknown.status, "rejected_dispatched_tool_mismatch")
        self.assertEqual(unknown.exact_tool_mismatches, ("ha_not_a_tool",))

    def test_identity_failures_pass_through_and_refuse(self):
        catalog = catalog_920_component()
        for kwargs, status in (
            ({"server_name": "not-ha-mcp"}, "server_identity_mismatch"),
            ({"protocol": "1999-01-01"}, "unsupported_protocol_version"),
        ):
            with self.subTest(status=status):
                admission = admit_reviewed_catalog_for_dispatch(
                    self._validation(catalog, **kwargs), (RELOAD_TOOL,)
                )
                self.assertEqual(admission.status, status)
                self.assertFalse(admission.admitted)

    def test_structural_drift_is_refused_whatever_the_exact_set(self):
        base = catalog_920_component()
        for kind, tools in _structural_variants(base.tools, "ha_get_state").items():
            with self.subTest(kind=kind):
                admission = admit_reviewed_catalog_for_dispatch(
                    self._validation(_with_tools(base, tools)), (RELOAD_TOOL,)
                )
                self.assertEqual(admission.status, "rejected_catalog_mismatch")
                self.assertFalse(admission.admitted)
                self.assertIsNone(admission.normalized_catalog_fingerprint)

    def test_every_structural_guard_fails_closed(self):
        validation = self._validation(catalog_920_component())
        for field, value in (
            ("observed_tool_count", 76),
            ("missing_tool_count", 1),
            ("additional_tool_count", 1),
            ("duplicated_tool_count", 1),
            ("unreviewed_tool_count", 1),
            ("invalid_descriptor_count", 1),
            ("classification_mismatch_count", 1),
            ("classification_or_invalid_tool_count", 1),
            ("observed_raw_catalog_fingerprint", None),
            ("expected_normalized_catalog_fingerprint", None),
            ("normalized_catalog_fingerprint", None),
            ("reviewed_accounted_count", 75),
            ("validation_status", "unsupported_runtime_fingerprint_model"),
        ):
            with self.subTest(field=field):
                changed = dataclasses.replace(validation, **{field: value})
                admission = admit_reviewed_catalog_for_dispatch(changed, (RELOAD_TOOL,))
                self.assertFalse(admission.admitted)
                self.assertIsNone(admission.normalized_catalog_fingerprint)

    def test_drift_diagnostics_are_bounded_and_counted(self):
        catalog = catalog_920()
        names = [
            tool["name"]
            for tool in catalog.tools
            if tool["name"] not in {RELOAD_TOOL, APP_ACTION_TOOL, APP_READ_TOOL}
        ][: MAX_REVIEWED_CATALOG_DIAGNOSTICS + 1]
        tools = list(catalog.tools)
        for name in names:
            tools = _drift_description(tools, name)
        admission = admit_reviewed_catalog_for_dispatch(
            self._validation(_with_tools(catalog, tools)),
            (RELOAD_TOOL, APP_ACTION_TOOL, APP_READ_TOOL),
        )
        self.assertEqual(admission.status, "accepted_unused_tool_drift")
        self.assertEqual(admission.unused_tool_drift_count, len(names))
        self.assertEqual(len(admission.unused_tool_drift), MAX_REVIEWED_CATALOG_DIAGNOSTICS)
        self.assertTrue(admission.unused_tool_drift_truncated)


