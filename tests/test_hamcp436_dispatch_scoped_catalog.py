def _fixture() -> dict:
    return json.loads(FIXTURE.read_text(encoding="utf-8"))


def _generator():
    spec = importlib.util.spec_from_file_location("hamcp436_generator", GENERATOR)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _canonical(value) -> str:
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def _with_tools(catalog: McpReadCatalog, tools) -> McpReadCatalog:
    return McpReadCatalog(
        catalog.protocol_version,
        catalog.server_name,
        catalog.server_version,
        tuple(tools),
        1.0,
    )


def catalog_920_component(**kwargs) -> McpReadCatalog:
    """The reviewed 9.2.0 catalog as served with the component installed."""

    descriptor = _fixture()["descriptor"]
    catalog = catalog_920(**kwargs)
    tools = [
        deepcopy(descriptor) if tool["name"] == REWRITTEN_TOOL else tool
        for tool in catalog.tools
    ]
    return _with_tools(catalog, tools)


def _drift_description(tools, name: str) -> list:
    changed = [deepcopy(tool) for tool in tools]
    target = next(tool for tool in changed if tool["name"] == name)
    target["description"] = f"{target.get('description') or ''} (drifted)"
    return changed


def _structural_variants(tools, other: str) -> dict[str, list]:
    tools = [deepcopy(tool) for tool in tools]
    index = next(i for i, tool in enumerate(tools) if tool["name"] == other)
    missing = [tool for tool in tools if tool["name"] != other]
    duplicate = [*tools, deepcopy(tools[index])]
    extra = [*tools, {**deepcopy(tools[index]), "name": "ha_unreviewed_extra"}]
    reordered = list(tools)
    reordered[0], reordered[1] = reordered[1], reordered[0]
    return {
        "missing": missing,
        "duplicate": duplicate,
        "extra": extra,
        "reordered": reordered,
    }


async def _run_operation(provider, operation: str):
    # As the gateway does at planning: on 9.2.0 the probe selects the
    # reviewed renamed add-on tools before an add-on restart can dispatch.
    await provider.probe(operation)
    if operation == "controlled_reload":
        return await provider.reload("automation", before_dispatch=lambda: None)
    if operation == "restart_addon":
        return await provider.restart_addon(OTHER_ADDON, before_dispatch=lambda: None)
    return await provider.restart_home_assistant(before_dispatch=lambda: None)


