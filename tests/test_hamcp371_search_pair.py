def _script():
    spec = importlib.util.spec_from_file_location("d6_search_pair", SR / "d6_search_pair.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def descriptor(variant):
    return deepcopy(PAIR["variants"][variant]["descriptor"])


def catalog(variant=None, search=None):
    """The reviewed 77-tool 9.2.0 catalog with ``ha_search`` replaced."""
    replacement = search if search is not None else descriptor(variant)
    return tuple(deepcopy(replacement) if tool["name"] == SEARCH else tool
                 for tool in useful.reviewed_catalog("9.2.0"))


def _search_content():
    for call, record in replay.public_calls("B/9.2.0"):
        if call["public_tool"] == SEARCH:
            return record["exchange"]["response"]["result"]["structuredContent"]
    raise AssertionError("no recorded 9.2.0 ha_search payload")


SEARCH_CONTENT = _search_content()
SIBLING = useful.NoRedirectUseful._delegated_read_case(None, "9.2.0")


def handler(name, arguments):
    if name == SEARCH:
        return deepcopy(SEARCH_CONTENT)
    if (name, arguments) == SIBLING.upstream:
        return deepcopy(SIBLING.structured)
    raise AssertionError(f"unexpected upstream call {name}")


@asynccontextmanager
async def session(tools):
    peer = RedirectPeer(version="9.2.0", form="strict_full", tools=tuple(tools), page_size=30,
                        call_handler=handler)
    with peer.serve():
        gateway = UpstreamReadGateway()
        gateway.configure(core._settings(peer.url))
        try:
            await asyncio.wait_for(gateway.initialize(FastMCP("x")), core.DEADLINE)
            yield gateway, peer
        finally:
            await asyncio.wait_for(gateway._transport.aclose(), core.DEADLINE)


async def run(tool, arguments):
    _telemetry, token = begin_request("synthetic-hamcp371-d6")
    try:
        return json.loads(await asyncio.wait_for(tool.run(deepcopy(arguments)), core.DEADLINE))
    finally:
        end_request(token)


def exposed(gateway):
    return gateway._registered_tool_registry.snapshot()


def quarantined(gateway):
    return {item.get("upstream_name")
            for item in gateway.health_snapshot().get("quarantined_tools", [])}


def third_descriptors():
    legacy, unified = descriptor("legacy"), descriptor("unified")
    hybrid = deepcopy(unified)
    hybrid["description"] = legacy["description"]
    partial = deepcopy(legacy)
    partial["inputSchema"]["properties"].pop("config_time_budget")
    extra = deepcopy(unified)
    extra["inputSchema"]["properties"]["forged"] = {"type": "boolean"}
    drift = deepcopy(unified)
    drift["description"] += " drift"
    unsafe = deepcopy(unified)
    unsafe["annotations"]["readOnlyHint"] = False
    return {"hybrid": hybrid, "legacy_minus_budget": partial, "unified_plus_property": extra,
            "unified_description_drift": drift, "unified_not_read_only": unsafe}


class PairBindingTests(unittest.TestCase):
    def test_the_committed_pair_is_what_the_script_generates(self):
        self.assertEqual(PAIR_FILE.read_text(encoding="utf-8"), _script().render())

    def test_module_constants_are_the_generated_pair(self):
        self.assertEqual([v.name for v in reads_9_2.SEARCH_VARIANTS], ["legacy", "unified"])
        for variant in reads_9_2.SEARCH_VARIANTS:
            with self.subTest(variant=variant.name):
                row = PAIR["variants"][variant.name]
                self.assertEqual(variant.catalog_fingerprint, row["catalog_fingerprint"])
                self.assertEqual(variant.strict_full_contract_fingerprint,
                                 row["strict_full_contract_fingerprint"])
                self.assertEqual(variant.input_schema_fingerprint, row["input_schema_fingerprint"])
                self.assertEqual(variant.description_fingerprint, row["description_fingerprint"])
                self.assertEqual(variant.runtime_contract_fingerprint,
                                 row["runtime_contract_fingerprint"])
                self.assertEqual(variant.runtime_contract_fingerprint, row["descriptor_sha256"])
                self.assertEqual(dict(variant.runtime_fields),
                                 row["runtime_contract_field_fingerprints"])
        self.assertEqual(reads_9_2.SEARCH_PAIR_DIGEST, PAIR["descriptor_pair_sha256"])
        self.assertEqual(reads_9_2.SEARCH_PAIR_DIGEST, schema_fingerprint(PAIR["descriptor_pair"]))
        self.assertEqual(reads_9_2.SEARCH_ENTRY_FINGERPRINT, PAIR["entry_fingerprint"])
        self.assertEqual(reads_9_2.SEARCH_REFERENCE_CONTRACT_FINGERPRINT,
                         PAIR["reference_contract_fingerprint"])
        self.assertEqual(reads_9_2.SEARCH_PUBLIC_SCHEMA_FINGERPRINT, PAIR["public_schema_fingerprint"])
        self.assertEqual(reads_9_2.SEARCH_POLICY_SHA256, PAIR["release"]["policy_sha256"])

    def test_the_binding_is_exact(self):
        pair = PAIR["descriptor_pair"]
        self.assertEqual((pair["version"], pair["source"]), ("9.2.0", core.SOURCE_920))
        self.assertEqual((RELEASE.version, RELEASE.source_commit), ("9.2.0", core.SOURCE_920))
        self.assertEqual(RELEASE.policy_sha256, reads_9_2.SEARCH_POLICY_SHA256)
        self.assertEqual(RELEASE.policy_resource, reads_9_2.SEARCH_POLICY_RESOURCE)
        self.assertEqual(PAIR["inputs"]["profile_b_receipt"]["sha256"],
                         "c707f5f78003f446e66fce096561eea18c4fbfe9b8f8df5a16ca883b4c45fee4")
        # The stored registry row and compiled entry keep the legacy descriptor.
        legacy = reads_9_2.SEARCH_VARIANTS[0]
        self.assertEqual(RELEASE.policy.by_name[SEARCH].input_schema_fingerprint,
                         legacy.input_schema_fingerprint)
        self.assertEqual(RELEASE.catalog_fingerprint, legacy.catalog_fingerprint)
        self.assertEqual(RELEASE.strict_full_contract_fingerprint,
                         legacy.strict_full_contract_fingerprint)

    def test_unified_differs_from_legacy_only_by_the_three_arguments_and_descriptions(self):
        legacy, unified = descriptor("legacy"), descriptor("unified")
        self.assertEqual(set(legacy["inputSchema"]["properties"])
                         - set(unified["inputSchema"]["properties"]), LEGACY_ARGUMENTS)
        self.assertTrue(set(unified["inputSchema"]["properties"])
                        <= set(legacy["inputSchema"]["properties"]))
        for key in set(legacy) - {"inputSchema", "description"}:
            self.assertEqual(legacy[key], unified[key], key)

    def test_the_public_schema_is_unchanged(self):
        schema = reads_9_2.PUBLIC_SCHEMAS[SEARCH]
        self.assertEqual(schema_fingerprint(schema), reads_9_2.SEARCH_PUBLIC_SCHEMA_FINGERPRINT)
        self.assertEqual(schema_fingerprint(schema), search_8_6.PUBLIC_SCHEMA_FINGERPRINT)
        self.assertTrue(LEGACY_ARGUMENTS <= set(schema["properties"]))

    def test_the_8_6_pair_and_its_tests_are_unchanged(self):
        for path, digest in FILES_8_6.items():
            with self.subTest(path=path):
                self.assertEqual(hashlib.sha256((ROOT / path).read_bytes()).hexdigest(), digest)


class ResolutionTests(unittest.TestCase):
    entry = RELEASE.policy.by_name[SEARCH]

    def test_each_variant_resolves_on_the_exact_release(self):
        for name in ("legacy", "unified"):
            with self.subTest(variant=name):
                variant = reads_9_2.resolve_search_variant(RELEASE, self.entry, descriptor(name))
                self.assertEqual(variant.name, name)

    def test_a_third_descriptor_resolves_to_nothing(self):
        for label, tool in third_descriptors().items():
            with self.subTest(case=label):
                self.assertIsNone(reads_9_2.resolve_search_variant(RELEASE, self.entry, tool))
                self.assertIs(reads_9_2.search_catalog_view(RELEASE, catalog(search=tool)), RELEASE)

    def test_foreign_or_altered_authority_is_untrusted(self):
        unified = descriptor("unified")
        cases = {
            # Real retired releases, frozen at 0f1adcb5 (HAMCP-437).
            "8.6.0": core.FOREIGN.by_version["8.6.0"],
            "9.1.2": core.FOREIGN.by_version["9.1.2"],
            "source": replace(RELEASE, source_commit="0" * 40),
            "policy_sha256": replace(RELEASE, policy_sha256="sha256:" + "0" * 64),
            "revoked": replace(RELEASE, revoked=True),
            "protocol": replace(RELEASE, allowed_protocol_versions=("2025-06-18",)),
        }
        for label, release in cases.items():
            with self.subTest(case=label):
                entry = release.policy.by_name.get(SEARCH)
                self.assertIsNone(reads_9_2.resolve_search_variant(release, entry, unified))
                self.assertIsNone(reads_9_2.search_capability_contract(release, entry))
        for label, entry in {
                "classification": replace(self.entry, classification="unreviewed"),
                "exposed_name": replace(self.entry, exposed_name="ha_search_forged"),
                "foreign_input": replace(self.entry, input_schema_fingerprint="0" * 64)}.items():
            with self.subTest(entry=label):
                self.assertIsNone(reads_9_2.resolve_search_variant(RELEASE, entry, unified))
        # Neither module's pair crosses into the other's release.
        self.assertIsNone(search_8_6.resolve_search_variant(RELEASE, self.entry, unified))
        release_86 = core.FOREIGN.by_version["8.6.0"]
        for tool in (t for t in useful.reviewed_catalog("8.6.0") if t["name"] == SEARCH):
            self.assertIsNone(reads_9_2.resolve_search_variant(
                release_86, release_86.policy.by_name[SEARCH], tool))

    def test_the_view_is_ephemeral(self):
        before = schema_fingerprint(repr(RELEASE))
        self.assertIs(reads_9_2.search_catalog_view(RELEASE, catalog("legacy")), RELEASE)
        view = reads_9_2.search_catalog_view(RELEASE, catalog("unified"))
        unified = reads_9_2.SEARCH_VARIANTS[1]
        self.assertIsNot(view, RELEASE)
        self.assertEqual(view.policy.by_name[SEARCH].input_schema_fingerprint,
                         unified.input_schema_fingerprint)
        self.assertEqual(view.catalog_fingerprint, unified.catalog_fingerprint)
        self.assertEqual(schema_fingerprint(repr(RELEASE)), before)
        self.assertEqual(RELEASE.policy.by_name[SEARCH].input_schema_fingerprint,
                         reads_9_2.SEARCH_VARIANTS[0].input_schema_fingerprint)

    def test_each_variant_catalog_validates_exactly(self):
        for name in ("legacy", "unified"):
            with self.subTest(variant=name):
                result = validate_reviewed_release_catalog(
                    RELEASE, observed_server_name="ha-mcp", observed_upstream_version="9.2.0",
                    observed_protocol_version="2025-03-26", tools=list(catalog(name)))
                self.assertTrue(result.valid, result)

    def test_variant_attribution_needs_both_fingerprints_from_one_variant(self):
        legacy, unified = reads_9_2.SEARCH_VARIANTS
        view_entry = reads_9_2.search_catalog_view(
            RELEASE, catalog("unified")).policy.by_name[SEARCH]
