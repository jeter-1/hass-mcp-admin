"""HAMCP-371 D6: the exact ha-mcp 9.2.0 ``ha_search`` descriptor pair.

Architect rulings 2026-11-15 22:26 CST (R-D6-1 to R-D6-3). ha-mcp 9.2.0
(``51e3aac7``, ``src/ha_mcp/transforms/component_search.py``) advertises a
trimmed ``unified`` ha_search when the component reports unified search, and
the reviewed ``legacy`` one otherwise. ``upstream_reads_9_2`` admits exactly
those two descriptors, generated by ``docs/evidence/hamcp371/sr/d6_search_pair.py``.

* Both variants are admitted exact on 9.2.0; any third descriptor is refused
  and quarantined, and its siblings stay usable.
* A flip between them at call time behaves as 8.6 did (the retired
  ``test_upstream_8_6_compatibility.test_known_transitions_retire_old_search_without_harming_sibling``):
  the pinned route refuses before dispatch and is quarantined, the sibling is
  unaffected, and the next fresh discovery admits the other variant.
* ``config_time_budget``, ``search_types`` and ``include_config`` are forwarded
  unchanged under both variants. The public schema does not change. Under
  ``unified`` a supplied ``config_time_budget`` adds one fixed warning
  (``search_budget_legacy_path_only``) and is not refused.
* Each result names the descriptor variant the route pinned and the live
  catalog matched before dispatch. That is the advertised descriptor, not proof
  of which upstream code path served the call.
* The 8.6 pair (``upstream_search_8_6.py``) is byte-identical to origin/main
  ``e741f2ed``. Its 8.6 test module is retired (HAMCP-437: it tested only old
  versions); the flip guard is ``test_a_flip_refuses_the_pinned_route_until_the_next_discovery``.

Offline: loopback synthetic peers, recorded S6 payloads, no Home Assistant.
"""
