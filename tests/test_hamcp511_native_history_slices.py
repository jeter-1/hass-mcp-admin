    async def test_native_pages_match_the_delegated_pages_with_fewer_core_requests(self):
        for case, golden in self.goldens["cases"].items():
            with self.subTest(case):
                recorder = Recorder(entity_id=parity.ENTITY)
                parity.seed(recorder)
                reader = FakeReader(recorder)
                codec = CursorCodec("history_slices", key=parity.CODEC_KEY, clock=lambda: parity.NOW_MS / 1000)
                service = HistorySliceService(reader, codec=codec, clock=lambda: parity.NOW_MS)
                pages, calls, cursor = [], [], None
                while True:
                    arguments = parity.arguments(case)
                    if cursor:
                        arguments["cursor"] = cursor
