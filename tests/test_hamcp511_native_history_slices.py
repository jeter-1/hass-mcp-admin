class LoopbackTests(unittest.IsolatedAsyncioTestCase):
    async def asyncSetUp(self):
        self.recorder = Recorder(entity_id=ENTITY)
        self.recorder.add(S0 - 10**6, "on")
        self.recorder.add(S0 + 10**6, "off")
        self.requests: list[tuple[str, str, str]] = []
        self.mode = "ok"
        self.release = asyncio.Event()

        async def handler(request):
            self.requests.append((request.method, request.raw_path, request.headers.get("Authorization", "")))
            if self.mode == "hang":
                await self.release.wait()
            if self.mode == "redirect" and request.path != "/redirected":
                raise web.HTTPFound("/redirected")
            if self.mode == "oversize":
                return web.Response(body=b" " * (MAX_READ_BYTES + 1), content_type="application/json")
            if self.mode == "error":
                return web.json_response({"message": "synthetic"}, status=500)
            start = request.match_info["start"]
            rows = self.recorder.period_body(request.query["filter_entity_id"], parse_us(start),
                                             parse_us(request.query["end_time"]))
            return web.json_response(rows)

        app = web.Application()
        app.router.add_route("GET", "/api/history/period/{start}", handler)
        app.router.add_route("*", "/{path:.*}", handler)
        self.runner = web.AppRunner(app, access_log=None)
        await self.runner.setup()
        site = web.TCPSite(self.runner, "127.0.0.1", 0)
        await site.start()
        self.settings = settings(f"http://127.0.0.1:{site._server.sockets[0].getsockname()[1]}")

    async def asyncTearDown(self):
        self.release.set()
        await self.runner.cleanup()

    async def read(self, reader=None):
        reader = reader or native.reader_factory(self.settings)()
        with lease() as telemetry:
            telemetry.error_code = None
            result = await reader.read(ENTITY, START, END, 0, 50)
            self.assertIsNone(telemetry.error_code)
        return result

    async def test_the_wire_request_is_exact(self):
        self.assertEqual(await self.read(), ([(S0, "on"), (S0 + 10**6, "off")], 2, False))
        [(method, raw_path, authorization)] = self.requests
        self.assertEqual(method, "GET")
        self.assertEqual(raw_path, "/api/history/period/2026-10-19T00:00:00.000000%2B00:00"
                                   "?end_time=2026-10-19T06:00:00.000000%2B00:00"
                                   f"&filter_entity_id={ENTITY}&minimal_response&no_attributes"
                                   "&significant_changes_only=1")
        self.assertTrue(authorization == "Bearer " + HA_TOKEN)

    async def test_an_oversize_body_is_unavailable(self):
        self.mode = "oversize"
        self.assertEqual(await self.read(), "core_read_unavailable")
        self.assertEqual(len(self.requests), 1)

    async def test_a_redirect_is_never_followed(self):
        self.mode = "redirect"
        self.assertEqual(await self.read(), "core_read_unavailable")
        self.assertEqual([path for _, path, _ in self.requests if path == "/redirected"], [])
        self.assertEqual(len(self.requests), 1)

    async def test_an_http_error_is_a_failed_read(self):
        self.mode = "error"
        self.assertEqual(await self.read(), "core_read_failed")
        self.assertEqual(len(self.requests), 1)

    async def test_a_hung_read_times_out_once_without_retry(self):
        self.mode = "hang"
