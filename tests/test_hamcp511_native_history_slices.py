class ParserTests(unittest.TestCase):
    def test_pinned_bodies_parse_with_exact_microseconds(self):
        rows = [(S0, "on"), (S0 + 1, "off"), (S0 + 10**6, "on"), (S1 - 1, "last")]
        self.assertEqual(native.parse_period(body(rows), ENTITY, S0, S1), rows)
        self.assertEqual(native.parse_period("[]", ENTITY, S0, S1), [])
        # A whole second renders without a fraction, as Core's isoformat().
        self.assertEqual(render(S0 + 10**6), "2026-10-19T00:00:01+00:00")
        self.assertEqual(render(S0 + 1), "2026-10-19T00:00:00.000001+00:00")

    def test_need_attribute_domains_keep_full_rows_and_repeats(self):
        rows = [(S0, "heat"), (S0 + 10, "heat"), (S0 + 20, "idle")]
        self.assertEqual(native.parse_period(body(rows, CLIMATE, full=True), CLIMATE, S0, S1), rows)
        # A minimal later row is not the pinned shape for these domains,
        self.assertIsNone(native.parse_period(body(rows, CLIMATE), CLIMATE, S0, S1))
        # and a full later row is not the pinned shape for the others.
        self.assertIsNone(native.parse_period(body(rows, ENTITY, full=True), ENTITY, S0, S1))
        self.assertEqual(native.NEED_ATTRIBUTE_DOMAINS,
                         {"climate", "humidifier", "input_datetime", "thermostat", "water_heater"})
        self.assertEqual(Recorder(entity_id=CLIMATE).query(S0, S1), [])

    def test_unpinned_bodies_are_refused(self):
        good = json.loads(body([(S0, "on"), (S0 + 10**6, "off")]))

        def edit(change):
            value = json.loads(json.dumps(good))
            change(value)
            return json.dumps(value)

        cases = {
            "extra key": edit(lambda v: v[0][1].update(extra=1)),
            "missing last_changed": edit(lambda v: v[0][1].pop("last_changed")),
            "wrong entity": edit(lambda v: v[0][0].update(entity_id="sensor.other_synthetic_511")),
            "unsorted": edit(lambda v: v[0][1].update(last_changed=render(S0 - 1))),
            "attributes": edit(lambda v: v[0][0].update(attributes={"synthetic": 1})),
            "changed differs": edit(lambda v: v[0][0].update(last_changed=render(S0 + 5))),
            "non-str state": edit(lambda v: v[0][1].update(state=3)),
            "offset time": edit(lambda v: v[0][1].update(last_changed="2026-10-19T01:00:00+01:00")),
            "naive time": edit(lambda v: v[0][1].update(last_changed="2026-10-19T00:00:01")),
            "at end": edit(lambda v: v[0][1].update(last_changed=render(S1))),
            "two lists": json.dumps(good + good),
            "empty inner list": "[[]]",
            "object body": '{"synthetic": 1}',
            "NaN": '[[{"state": NaN, "last_changed": "x"}]]',
            "duplicate key": '[[{"state": "a", "state": "b", "last_changed": "x"}]]',
            "not json": "synthetic <html>",
        }
        for label, text in cases.items():
            with self.subTest(label):
                self.assertIsNone(native.parse_period(text, ENTITY, S0, S1))
        for value in (None, b"[]", ["synthetic"], 1):
            with self.subTest(type(value).__name__):
                self.assertIsNone(native.parse_period(value, ENTITY, S0, S1))


