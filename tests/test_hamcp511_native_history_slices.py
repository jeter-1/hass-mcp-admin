class SlotTests(unittest.IsolatedAsyncioTestCase):
    async def hold(self, slots, caller, log, release: asyncio.Event):
        async with slots.hold(caller):
            log.append(caller)
            await release.wait()

    async def settle(self):
        for _ in range(5):
            await asyncio.sleep(0)

    def busy_scope(self, raised) -> str:
        self.assertEqual(raised.exception.code, ErrorCode.READ_BUSY)
        return raised.exception.details["scope"]

    async def test_two_callers_run_and_a_third_waits_for_a_global_slot(self):
        slots, log, release = ReadSlots(), [], [asyncio.Event() for _ in range(3)]
        tasks = [asyncio.create_task(self.hold(slots, f"synthetic_caller_{n}", log, release[n])) for n in range(3)]
        await self.settle()
        self.assertEqual((log, slots.running()), (["synthetic_caller_0", "synthetic_caller_1"], 2))
        release[0].set()
        await self.settle()
        self.assertEqual((log[-1], slots.running()), ("synthetic_caller_2", 2))
        for event in release:
            event.set()
        await asyncio.gather(*tasks)
        self.assertEqual((slots.running(), slots._callers, slots._admitted), (0, {}, {}))

    async def test_one_caller_runs_one_waits_three_in_order_and_refuses_the_fifth(self):
        slots, log, release = ReadSlots(), [], [asyncio.Event() for _ in range(4)]
        tasks = []
        for n in range(4):
            tasks.append(asyncio.create_task(self.hold(slots, CALLER, log, release[n])))
            await self.settle()
        self.assertEqual((len(log), slots.running()), (1, 1))
        with self.assertRaises(GovernanceError) as raised:
            async with slots.hold(CALLER):
                self.fail("a fifth read must not start")
        self.assertEqual(self.busy_scope(raised), "caller")
        for n in range(4):
            release[n].set()
            await self.settle()
            self.assertEqual(len(log), min(n + 2, 4))
        await asyncio.gather(*tasks)
        self.assertEqual((slots._callers, slots._admitted), ({}, {}))

    async def test_fifo_order_for_one_caller(self):
        slots, order, release = ReadSlots(), [], asyncio.Event()

        async def hold(label):
            async with slots.hold(CALLER):
                order.append(label)
                await release.wait()
                release.clear()

        tasks = []
        for label in ("first", "second", "third", "fourth"):
            tasks.append(asyncio.create_task(hold(label)))
            await self.settle()
        for _ in range(4):
            release.set()
            await self.settle()
        await asyncio.gather(*tasks)
        self.assertEqual(order, ["first", "second", "third", "fourth"])

    async def test_a_wait_past_the_deadline_is_busy_with_its_scope(self):
        slots, release = ReadSlots(wait_seconds=0.05), asyncio.Event()
        holders = [asyncio.create_task(self.hold(slots, name, [], release))
                   for name in ("synthetic_caller_0", "synthetic_caller_1")]
        await self.settle()
        with self.assertRaises(GovernanceError) as raised:
            async with slots.hold("synthetic_caller_0"):
                self.fail("the caller slot is held")
        self.assertEqual(self.busy_scope(raised), "caller")
        with self.assertRaises(GovernanceError) as raised:
            async with slots.hold("synthetic_caller_2"):
                self.fail("both global slots are held")
        self.assertEqual(self.busy_scope(raised), "global")
        self.assertEqual(slots.running(), 2)
        release.set()
        await asyncio.gather(*holders)
        self.assertEqual((slots.running(), slots._callers, slots._admitted), (0, {}, {}))

    async def test_cancelled_waiters_and_holders_free_their_slots(self):
        slots, log, release = ReadSlots(global_reads=1), [], asyncio.Event()
        holder = asyncio.create_task(self.hold(slots, "synthetic_caller_0", log, asyncio.Event()))
        waiter = asyncio.create_task(self.hold(slots, "synthetic_caller_1", log, release))
        same = asyncio.create_task(self.hold(slots, "synthetic_caller_0", log, release))
        await self.settle()
        waiter.cancel()
        same.cancel()
        await self.settle()
        holder.cancel()
        await asyncio.gather(holder, waiter, same, return_exceptions=True)
        self.assertEqual(log, ["synthetic_caller_0"])
        self.assertEqual((slots.running(), slots._callers, slots._admitted), (0, {}, {}))
        async with slots.hold("synthetic_caller_1"):
            self.assertEqual(slots.running(), 1)

    def test_read_busy_is_the_shared_retryable_409(self):
        definition = error_definition(ErrorCode.READ_BUSY)
        self.assertEqual((ErrorCode.READ_BUSY.value, definition.retryable, definition.http_status),
                         ("read_busy", True, 409))
        for scope, expected in (("caller", "caller"), ("global", "global"), ("synthetic", "global")):
            error = c.HistorySlicesError("read_in_progress", scope=scope)
            code, message, retryable, details = map_exception(error)
            self.assertEqual((code, retryable), (ErrorCode.READ_BUSY, True))
            self.assertEqual(message, "Another history read is in progress; retry after it completes.")
            self.assertEqual(details, {"reason": "read_in_progress", "fallback_occurred": False, "scope": expected})
        self.assertEqual((c.READS_PER_CALLER, c.QUEUED_READS_PER_CALLER, c.READS_GLOBAL, c.READ_WAIT_SECONDS),
                         (1, 3, 2, 10))


class GatedClient:
    """The fake Core client behind a gate: counts requests in flight per caller."""

    def __init__(self, recorder: Recorder):
        self.inner = FakeReader(recorder)
        self.release = asyncio.Event()
        self.in_flight = 0
        self.peak = 0
        self.callers: list[str] = []

    async def request(self, *args, **kwargs):
        self.callers.append(current_telemetry().caller_id)
        self.in_flight += 1
        self.peak = max(self.peak, self.in_flight)
        try:
            await self.release.wait()
            return await self.inner.request(*args, **kwargs)
        finally:
            self.in_flight -= 1


class ServiceSlotTests(unittest.IsolatedAsyncioTestCase):
    def setUp(self):
        self.recorder = Recorder(entity_id=ENTITY)
        self.recorder.add(S0 - 10**6, "on")
        self.recorder.add(S0 + 10**6, "off")
        self.client = GatedClient(self.recorder)

    def tearDown(self):
        self.assertEqual(self.client.inner.violations, [])

    def service(self, slots: ReadSlots | None = None) -> HistorySliceService:
        codec = CursorCodec("history_slices", key=b"n" * 32, clock=lambda: NOW_MS / 1000)
        return HistorySliceService(lambda: native.NativeHistoryReader(self.client), codec=codec,
                                   clock=lambda: NOW_MS, slots=slots)

    async def read(self, service, caller, authorizer=lambda: True):
        with lease(authorizer, caller):
            return await service.read({"entity_id": ENTITY, "start": "2026-10-19T00:00:00Z",
                                       "end": "2026-10-19T01:00:00Z"})

    async def test_at_most_two_reads_reach_core_at_once(self):
        service = self.service()
        tasks = [asyncio.create_task(self.read(service, f"synthetic_caller_{n}")) for n in range(3)]
        for _ in range(10):
            await asyncio.sleep(0)
        self.assertEqual((self.client.in_flight, service.slots.running()), (2, 2))
        self.assertEqual(sorted(self.client.callers), ["synthetic_caller_0", "synthetic_caller_1"])
        self.client.release.set()
        pages = await asyncio.gather(*tasks)
        self.assertEqual(self.client.peak, 2)
        self.assertTrue(all(page["complete"] for page in pages))
        self.assertEqual(service.slots.running(), 0)

    async def test_anonymous_is_refused_before_queueing(self):
        service = self.service()
        with self.assertRaises(GovernanceError) as raised:
            await self.read(service, "anonymous")
        self.assertEqual(raised.exception.details["reason"], "history_route_unavailable")
        self.assertEqual((self.client.callers, service.slots._admitted), ([], {}))

    async def test_a_lease_lost_while_waiting_dispatches_nothing(self):
        service = self.service(ReadSlots(global_reads=1))
        first = asyncio.create_task(self.read(service, "synthetic_caller_0"))
        for _ in range(5):
            await asyncio.sleep(0)
        waiting = [True]
        second = asyncio.create_task(self.read(service, "synthetic_caller_1", lambda: waiting[0]))
        for _ in range(5):
            await asyncio.sleep(0)
        self.assertEqual(service.slots._admitted, {"synthetic_caller_0": 1, "synthetic_caller_1": 1})
        waiting[0] = False
        self.client.release.set()
        self.assertTrue((await first)["complete"])
        with self.assertRaises(GovernanceError) as raised:
            await second
