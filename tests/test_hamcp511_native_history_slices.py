@contextmanager
def lease(authorizer=lambda: True, caller: str = CALLER):
    """One request context carrying the tool's Core lease."""

    telemetry, token = begin_request()
    telemetry.caller_id = caller
    telemetry.core_dispatch_authorizer = authorizer
    try:
        yield telemetry
    finally:
        end_request(token)


def body(rows, entity_id: str = ENTITY, *, full: bool = False) -> str:
    return json.dumps([[core_row(entity_id, ts_us, state, full=index == 0 or full)
                        for index, (ts_us, state) in enumerate(rows)]])


class Client:
    """A fake Core REST client: records each request, replies or raises."""

    def __init__(self, reply=None):
        self.reply = reply if reply is not None else body([(S0, "on"), (S0 + 10**6, "off")])
        self.calls: list[dict] = []
        self.on_request = None

    async def request(self, method, path, body=None, raw=False, expected_statuses=frozenset(), **kwargs):
        telemetry = current_telemetry()
        self.calls.append({"method": method, "path": path, "body": body, "raw": raw,
                           "expected_statuses": expected_statuses, "kwargs": kwargs,
                           "single_read": SINGLE_READ.get()})
        if self.on_request is not None:
            self.on_request(telemetry)
        if isinstance(self.reply, BaseException):
            # The real transport records the failure as the call's error.
            telemetry.error_code = "synthetic_transport_error"
            raise self.reply
        return self.reply


