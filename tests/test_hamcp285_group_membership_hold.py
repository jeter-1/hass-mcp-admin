class GroupHoldAssertions:
    entity: str

    def assert_held(self, plan: dict[str, Any], binding: dict[str, Any], *,
                    groups: list[tuple[str, str, int | None]],
                    consequence: str = "unknown",
                    reason: str = UNATTRIBUTED,
                    unresolved: tuple[str, ...] = ()) -> dict[str, Any]:
        decision = plan["policy_decision"]
        self.assertEqual(decision["policy_class"], "elevated_admin", decision)
        self.assertEqual(decision["physical_consequence"], consequence)
        self.assertEqual(plan["risk"]["level"], "high")
        self.assertTrue(plan["approval_actionable"])
        # The exact execution contract is unaffected: only consequence evidence.
        self.assertTrue(binding["execution_contract_complete"])
        self.assertTrue(binding["execution_eligible"])
        self.assertEqual(binding["execution_block_reason_codes"], [])
        self.assertFalse(binding["consequence_evidence_complete"])
        self.assertIn(reason, binding["consequence_uncertainty_reason_codes"])
        hold = binding.get("group_membership_hold")
        self.assertIsInstance(hold, dict, "binding must carry the hold")
        self.assertEqual(hold["reason_code"], reason)
        self.assertEqual(
            [(item["group_entity_id"], item["membership"], item["depth"])
             for item in hold["groups"]],
            groups,
        )
        self.assertEqual(hold["membership_resolved"], not unresolved)
        self.assertEqual(hold["unresolved_reason_codes"], list(unresolved))
        projection = binding["dependency_lock_projection"]
        self.assertTrue(projection["coarse_automation_fence"])
        self.assertIn(reason, projection["coarse_automation_fence_reason_codes"])
        self.assertTrue(projection["conservative_helper_dependency"])
        modes = self.lock_modes(plan)
        self.assertEqual(modes["reload:automation"], LockMode.EXCLUSIVE)
        self.assertEqual(modes[unconstrained_helper_dependency_lock_key()],
                         LockMode.SHARED)
        self.assertEqual(modes[helper_dependency_lock_key(self.entity)],
                         LockMode.SHARED)
        notes = [item for item in plan["risk"]["warnings"] if HOLD_NOTE in item]
        self.assertEqual(len(notes), 1, plan["risk"]["warnings"])
        for group_id, membership, _ in groups:
            if membership != "possible":
                self.assertIn(group_id, notes[0])
            else:  # a possible group is not stated as a membership
                self.assertNotIn(group_id, notes[0])
        self.assertEqual("and more groups" in notes[0], hold["groups_truncated"])
        for code in unresolved:
            self.assertIn(code, notes[0])
        return hold

    def assert_not_held(self, plan: dict[str, Any], binding: dict[str, Any]) -> None:
        self.assertNotIn("group_membership_hold", binding)
        self.assertFalse(any(HOLD_NOTE in item for item in plan["risk"]["warnings"]))
        self.assertNotIn(UNATTRIBUTED, binding["consequence_uncertainty_reason_codes"])
        self.assertNotIn(UNRESOLVED, binding["consequence_uncertainty_reason_codes"])

    def assert_group_consumer_unattributed(self, binding: dict[str, Any],
                                           automation: str) -> None:
        """The documented HAMCP-287 limitation: the consumer is not named."""

        self.assertNotIn(f"automation.{automation}",
                         binding["relevant_downstream_object_ids"])
        self.assertNotIn(automation,
                         binding["dependency_lock_projection"]["automation_resource_ids"])

    def assert_consumer_attributed(self, binding: dict[str, Any],
                                   automation: str) -> None:
        self.assertIn(f"automation.{automation}",
                      binding["relevant_downstream_object_ids"])
        self.assertIn(automation,
                      binding["dependency_lock_projection"]["automation_resource_ids"])


