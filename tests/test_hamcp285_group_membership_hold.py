GROUP_FORMS = ("state_trigger", "state_condition", "is_state")


def group_state(group_id: str, members: Any) -> dict[str, Any]:
    return {"entity_id": group_id, "state": "off",
            "attributes": {"entity_id": members}}


def group_consumer(relation: str, *, group: str = "group.x",
                   entity: str | None = None) -> dict[str, Any]:
    """One automation that locks a door, referencing the group by *relation*."""

    triggers: list[dict[str, Any]] = [{"trigger": "time_pattern", "minutes": "/5"}]
    conditions: list[dict[str, Any]] = []
    if relation == "state_trigger":
        triggers = [{"trigger": "state", "entity_id": group, "to": "on"}]
    elif relation == "state_condition":
        conditions = [{"condition": "state", "entity_id": group, "state": "on"}]
    elif relation == "is_state":
        conditions = boolean_fixtures.template(
            "{{ is_state('%s', 'on') }}" % group
        )
    elif relation == "expand":
        conditions = boolean_fixtures.template(
            "{{ expand('%s') | selectattr('state', 'eq', 'on') "
            "| list | count > 0 }}" % group
        )
    elif relation == "literal":
        triggers = [{"trigger": "state", "entity_id": entity, "to": "on"}]
    else:
        raise AssertionError(relation)
    return {
        "alias": f"Group consumer {relation}",
        "triggers": triggers,
        "conditions": conditions,
        "actions": [{"action": "lock.lock",
                     "target": {"entity_id": "lock.synthetic_door"}}],
    }


