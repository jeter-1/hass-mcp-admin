"""HAMCP-285 R1-H1: input helpers that are group members are held elevated.

An automation that references ``group.x`` in a state trigger, a state
condition, or ``is_state('group.x', ...)`` runs when a member helper changes
the group state (pinned Core ``group/entity.py``), but the dependency index
attributes only literal and ``expand`` references to the member.  Until
precise group attribution exists (HAMCP-287), the target-scoped
input_boolean (v14) and input_select (v2) bindings hold a member helper:
``elevated_admin``, consequence ``unknown``, risk ``high``, the coarse
automation fence, and a disclosure naming each group.  Membership comes from
the same bounded ``expand`` authority the index reads for ``expand()``; when
it cannot be resolved the helper is treated as a possible member.

A helper in no group keeps the 2630d901 output byte for byte: the
``NonMemberDigestTests`` digests were generated by
``tests/hamcp285_nonmember_digests.py`` against an exact checkout of
2630d901.

Every service test drives the shipped governance service, F3 runtime and
runtime reader over a real ``DependencyIndex`` of a synthetic installation,
minimal or with unrelated noise.  No test reaches a network, a live Home
Assistant, or the ha-mcp provider.
"""

