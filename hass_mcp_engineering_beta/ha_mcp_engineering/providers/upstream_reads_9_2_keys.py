"""Closed 9.2.0 key sets for the compiled public reads (HAMCP-371 S10).

On ha-mcp 9.2.0 a key outside a read's reviewed key set is withheld and
counted, not a whole-read refusal (21:36 record, items 7 to 12). ``ROWS`` is
the output-key contract (``tests/fixtures/ha_mcp_9_2_0/output-key-contract.json``,
generated by ``docs/evidence/hamcp371/s7/generate_output_key_contract.py``); a
test asserts equality. Each read then runs its unedited 9.1 projection, or the
9.2.0 override in ``upstream_reads_9_2_entities`` (zone and services).

- ``admitted`` keys are kept; ``drops`` are policy drops, removed and counted
  apart; any other name is withheld and counted. Counts are distinct names,
  each capped at 999; names are never disclosed (item 10).
- ``OPEN_RULED`` and a row's ``open`` containers are integration- or
  user-defined content: kept whole and not counted (item 11).
- ``maps`` are containers whose dict keys are data (service names, domains);
  their values are closed rows, ``levels`` deep.
- ``types`` admits a key with one JSON value type only (S10-2 ruling); a value
  of another type is withheld and counted as one more withheld name.
- An upstream warning passes when it equals a reviewed string or starts with a
  reviewed prefix; a prefix rule may replace the text with a fixed Engineering
  sentence. Any other warning is removed, counted per occurrence and the fixed
  code ``upstream_warning_replaced`` is appended once to that list (item 12).
- The three counts sit at the top level of the read's ``data`` (D1).
- HAMCP-410 (HAAC-E042): when withholding empties every row of a non-empty
  collection (a list of objects, or an object whose values are all objects),
  ``engineering_notes`` carries ``COLLECTION_WITHHELD`` and the read is partial,
  so an emptied collection never reads as complete.

The blueprint, system health, integration and app reads use their own shipped
projections and are not routed here; ``ha_get_history`` (S9) and
``ha_get_device`` (N26) keep their own modules.
"""
