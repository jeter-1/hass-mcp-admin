def _names(value: Any, row: KeySet, acc: set) -> set:
    """The contract's distinct-name walk (generate_output_key_contract.names)."""

    if isinstance(value, dict):
        for key, item in value.items():
            acc.add(key)
            if key in row.types and type(item) is not row.types[key]:
                # Not a string, so never an admitted name.
                acc.add((key, "value_type"))
                continue
            if key in row.opened or key in row.drops:
                continue
            if key in row.maps:
                _map_names(item, row.maps[key], row, acc)
            else:
                _names(item, row, acc)
    elif isinstance(value, list):
        for item in value:
            _names(item, row, acc)
    return acc


def _map_names(value: Any, levels: int, row: KeySet, acc: set) -> None:
    if levels == 0 or not isinstance(value, dict):
        _names(value, row, acc)
        return
    for item in value.values():
        _map_names(item, levels - 1, row, acc)


class _Warnings:
    """Reviewed warnings pass; every other one is replaced and counted.

    ``collapsed`` counts the row collections the key set emptied (HAMCP-410).
    """

    def __init__(self, row: KeySet):
        self.row = row
        self.replaced = 0
        self.collapsed = 0

    def filter(self, warnings: list) -> list:
        kept, replaced = [], 0
        for text in warnings:
            if type(text) is str and text in self.row.warnings:
                kept.append(text)
                continue
            for prefix, replacement in self.row.prefixes:
                if type(text) is str and text.startswith(prefix):
                    kept.append(text if replacement is None else replacement)
                    break
            else:
                replaced += 1
        if replaced:
            kept.append(REPLACED_WARNING)
        self.replaced += replaced
        return kept


def _keep(value: Any, row: KeySet, warnings: _Warnings) -> Any:
    if isinstance(value, dict):
        kept = {}
        for key, item in value.items():
            if key not in row.admitted:
                continue
            if key in row.types and type(item) is not row.types[key]:
                continue
            if key in row.opened:
                kept[key] = item
                continue
            if key in row.maps:
                kept[key] = _keep_map(item, row.maps[key], row, warnings)
            elif key == "warnings" and isinstance(item, list):
                kept[key] = warnings.filter(item)
            else:
                kept[key] = _keep(item, row, warnings)
            if _emptied(item, kept[key]):
                warnings.collapsed += 1
        return kept
    if isinstance(value, list):
        return [_keep(item, row, warnings) for item in value]
    return value


def _emptied(item: Any, kept: Any) -> bool:
    """A non-empty row collection whose every row lost every field (HAMCP-410).

    A collection is a list of objects or an object whose values are all
    objects; it was emptied when some upstream row had a field and no kept row
    has one (an unmapped map whose data keys were all withheld keeps ``{}``).
    """

    if isinstance(item, list):
        rows, kept_rows = item, kept
    elif isinstance(item, dict):
        rows = list(item.values())
        kept_rows = list(kept.values()) if isinstance(kept, dict) else []
    else:
        return False
    if not rows or not all(isinstance(r, dict) for r in rows):
        return False
    return any(rows) and not any(kept_rows)


def _keep_map(value: Any, levels: int, row: KeySet, warnings: _Warnings) -> Any:
    if levels == 0 or not isinstance(value, dict):
        return _keep(value, row, warnings)
    return {key: _keep_map(item, levels - 1, row, warnings) for key, item in value.items()}


def projection(tool: str, inner: Callable) -> Callable:
    """Row ``tool``: withhold and count, then the compiled projection ``inner``."""

    row = ROWS[tool]

    def project(payload: Any, arguments: dict) -> dict:
        if type(payload) is not dict:
            raise ValueError("invalid_response")
        names = _names(payload, row, set())
        withheld = len(names - row.admitted - row.drops)
        dropped = len(names & row.drops)
        warnings = _Warnings(row)
        projected = inner(_keep(payload, row, warnings), arguments)
        if type(projected) is not dict or set(ENGINEERING_ADDED[:3]) & set(projected):
            raise ValueError("invalid_response")
        projected["fields_withheld"] = min(withheld, COUNT_CAP)
        projected["fields_dropped_by_policy"] = min(dropped, COUNT_CAP)
        projected["upstream_warnings_replaced"] = min(warnings.replaced, COUNT_CAP)
        if warnings.collapsed:
            notes = projected.get(NOTES)
            if notes is None:
                notes = projected[NOTES] = []
            if type(notes) is not list:
                raise ValueError("invalid_response")
            if COLLECTION_WITHHELD not in notes:
                notes.append(COLLECTION_WITHHELD)
        return projected

    return project


def completeness(inner: Callable, texts: dict | None = None) -> Callable:
    """The compiled rule, its 9.1-worded texts mapped, and a replaced warning partial."""

    def rule(payload: Any) -> tuple[bool, list[str]]:
        partial, warnings = inner(payload)
        warnings = [(texts or {}).get(text, text) for text in warnings]
        if isinstance(payload, dict) and payload.get("upstream_warnings_replaced"):
            partial = True
            if REPLACED_PARTIAL not in warnings:
                warnings.append(REPLACED_PARTIAL)
        notes = payload.get(NOTES) if isinstance(payload, dict) else None
        if isinstance(notes, list) and COLLECTION_WITHHELD in notes:
            partial = True
            if COLLECTION_WITHHELD not in warnings:
                warnings.append(COLLECTION_WITHHELD)
        return partial, warnings

    return rule


def bucket_withheld_names(payload: Any, bucket: str) -> frozenset:
    """The names Row 25 withholds from one ``ha_search`` bucket's records.

    HAMCP-501 W4 (decision D1, as relayed by the architect): the native search
    sub-calls disclose the record fields Row 25 withheld from their pages. W6
    S1 b+ (approved by Josh as relayed by the architect) adds the automation,
    script and scene sub-calls to the dashboard and flow-helper ones, and
    HAMCP-447 makes dashboards native. This is
    :func:`projection`'s distinct-name walk over ``payload[bucket]`` only, so
    page-level names (``partial_reason``) are not record names. A value of a
    type its key does not admit counts under its own key. The names stay in
    Engineering's memory; a reply emits only their count. Raises
    ``ValueError`` (``invalid_response``) on any other shape.
    """

    row = ROWS["ha_search"]
    if type(payload) is not dict or bucket not in (
        "automations", "scripts", "scenes", "helpers",
    ):
        raise ValueError("invalid_response")
    records = payload.get(bucket)
    if type(records) is not list:
        raise ValueError("invalid_response")
    names = {
        name[0] if type(name) is tuple else name
        for name in _names(records, row, set()) - row.admitted - row.drops
    }
    if not all(type(name) is str for name in names):
        raise ValueError("invalid_response")
    return frozenset(names)


