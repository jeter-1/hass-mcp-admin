#!/usr/bin/env python3
"""HAMCP-371 D8 (ruling 2026-11-16 06:05 CST): exact-path whitespace entries for one SR run.

Inputs are the run's SHA256SUMS and ``git diff --cached --check BASE -- RUN`` (the
committed and staged run files against BASE). A file that git flags must be listed
in SHA256SUMS and must still match its listed sha256; it then gets one exact-path
``-text -whitespace`` entry. Any flagged file outside SHA256SUMS, any hash mismatch
or any quoted path stops with exit 2: that is a stop-and-report, never an entry.

Prints a JSON report. With ``--write`` the block (a comment naming the run and its
SHA256SUMS, then the entries) is appended to .gitattributes; a run that already has
a D8 block is refused. No globs are ever written.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path, PurePosixPath

ROOT = Path(__file__).resolve().parents[4]
SR = PurePosixPath("docs/evidence/hamcp371/sr")
SUMS_LINE = re.compile(r"^([0-9a-f]{64})  (\S+)$")
CHECK_LINE = re.compile(r"^(\S+):(\d+): (.+)$")


class StopAndReport(Exception):
    pass


def _git(root: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["git", "-C", str(root), *args], capture_output=True, text=True)


def read_sums(root: Path, run: PurePosixPath) -> dict[str, str]:
    sums = {}
    for number, line in enumerate((root / run / "SHA256SUMS").read_text(encoding="utf-8").splitlines(), 1):
        match = SUMS_LINE.fullmatch(line)
        if not match:
            raise StopAndReport(f"SHA256SUMS line {number} is not '<sha256>  <path>'")
        sums[str(run / match.group(2))] = match.group(1)
    return sums


def flagged_paths(root: Path, base: str, run: PurePosixPath) -> dict[str, list[int]]:
    result = _git(root, "diff", "--cached", "--check", base, "--", str(run))
    if result.returncode not in (0, 2):
        raise StopAndReport(f"git diff --check failed: {result.stderr.strip()}")
    flagged: dict[str, list[int]] = {}
    for line in result.stdout.splitlines():
        if line.startswith(("+", "-")):
            continue
        match = CHECK_LINE.fullmatch(line)
        if not match or match.group(1).startswith('"'):
            raise StopAndReport(f"unparsed git diff --check line: {line!r}")
        flagged.setdefault(match.group(1), []).append(int(match.group(2)))
    return flagged


def entries_for(root: Path, base: str, run_name: str) -> dict:
    run = SR / run_name
    if "/" in run_name or not (root / run / "SHA256SUMS").is_file():
        raise StopAndReport(f"{run} is not an SR run directory with SHA256SUMS")
    sums = read_sums(root, run)
    flagged = flagged_paths(root, base, run)
    entries = []
    for path in sorted(flagged):
        if path not in sums:
            raise StopAndReport(f"{path} fails git diff --check and is not in {run}/SHA256SUMS")
        if hashlib.sha256((root / path).read_bytes()).hexdigest() != sums[path]:
            raise StopAndReport(f"{path} does not match its {run}/SHA256SUMS sha256")
        entries.append({"path": path, "sha256": sums[path], "lines": flagged[path]})
    header = (f"# HAMCP-371 D8: {run_name} files listed in {run}/SHA256SUMS that fail\n"
              f"# git diff --check; generated by {SR}/d8_gitattributes.py.\n")
    block = header + "".join(f"{e['path']} -text -whitespace\n" for e in entries)
    return {"run": str(run), "base": base, "entries": entries,
            "block": block if entries else ""}


def write_block(root: Path, report: dict) -> None:
    attributes = root / ".gitattributes"
    text = attributes.read_text(encoding="utf-8")
    if f"# HAMCP-371 D8: {PurePosixPath(report['run']).name} " in text:
        raise StopAndReport(f"{report['run']} already has a D8 block")
    if not text.endswith("\n"):
        raise StopAndReport(".gitattributes does not end with a newline")
    attributes.write_text(text + report["block"], encoding="utf-8")


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("run", help="run directory name under docs/evidence/hamcp371/sr/")
    parser.add_argument("--base", required=True, help="base commit, e.g. origin/main")
    parser.add_argument("--write", action="store_true", help="append the block to .gitattributes")
    args = parser.parse_args(argv)
    try:
        report = entries_for(ROOT, args.base, args.run)
        if args.write and report["entries"]:
            write_block(ROOT, report)
    except StopAndReport as exc:
        print(json.dumps({"stop_and_report": str(exc)}, indent=1))
        return 2
    print(json.dumps(report, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
